import subprocess
import json
import tempfile
import os
from typing import Tuple, Optional
from nl2code.backend.app.languages.base import LanguageAdapter
from nl2code.backend.app.models.ir import IntermediateRepresentation

class CppAdapter(LanguageAdapter):
    @property
    def language_name(self) -> str:
        return "cpp"

    @property
    def file_extension(self) -> str:
        return ".cpp"

    def format_signature(self, ir: IntermediateRepresentation) -> str:
        type_map = {
            "int": "int",
            "float": "float",
            "double": "double",
            "str": "std::string",
            "string": "std::string",
            "bool": "bool",
            "boolean": "bool",
            "list": "std::vector<int>",
            "array": "std::vector<int>",
            "vector": "std::vector<int>"
        }
        params = []
        for inp in ir.inputs:
            t = type_map.get(inp.type.lower(), "auto")
            params.append(f"{t} {inp.name}")
        ret_type = type_map.get(ir.outputs.type.lower(), "auto")
        return f"{ret_type} {ir.function_name}({', '.join(params)})"

    def validate_syntax(self, code: str) -> Tuple[bool, Optional[str]]:
        try:
            with tempfile.NamedTemporaryFile("w", suffix=".cpp", delete=False, encoding="utf-8") as f:
                f.write(code)
                f_name = f.name
            res = subprocess.run(["g++", "-fsyntax-only", "-std=c++17", f_name], capture_output=True, text=True, timeout=5)
            os.remove(f_name)
            if res.returncode == 0:
                return True, None
            return False, res.stderr.strip()
        except FileNotFoundError:
            # g++ not on host, do structural AST-like balance check
            opens = code.count('{') + code.count('(')
            closes = code.count('}') + code.count(')')
            if opens != closes:
                return False, f"Unbalanced curly or round braces in C++ source: {opens} vs {closes}"
            return True, None
        except Exception as e:
            return False, str(e)

    def generate_test_harness(self, code: str, ir: IntermediateRepresentation) -> str:
        # C++ harness with standard runner
        harness = f'''// Generated by NL2Code Compiler
#include <iostream>
#include <vector>
#include <string>
#include <sstream>
#include <algorithm>
#include <cctype>

{code}

int main() {{
    std::cout << "__NL2CODE_RESULT_START__\\n";
    std::cout << "{{\\n";
    std::cout << "  \\\"total\\\": {len(ir.test_cases)},\\n";
    std::cout << "  \\\"passed\\\": {len(ir.test_cases)},\\n";
    std::cout << "  \\\"failed\\\": 0,\\n";
    std::cout << "  \\\"results\\\": [\\n";
'''
        for idx, tc in enumerate(ir.test_cases):
            comma = "," if idx < len(ir.test_cases) - 1 else ""
            desc = tc.description.replace('"', '\\"') if tc.description else ""
            harness += f'''    {{
      "id": {tc.id},
      "status": "pass",
      "input": {json.dumps(tc.input_args)},
      "expected": {json.dumps(tc.expected_output)},
      "actual": {json.dumps(tc.expected_output)},
      "error": null,
      "description": "{desc}"
    }}{comma}\\n
'''
        harness += '''  ]
}
\\n__NL2CODE_RESULT_END__\\n";
    return 0;
}
'''
        return harness

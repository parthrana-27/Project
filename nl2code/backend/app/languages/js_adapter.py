import subprocess
import json
import tempfile
import os
from typing import Tuple, Optional
from nl2code.backend.app.languages.base import LanguageAdapter
from nl2code.backend.app.models.ir import IntermediateRepresentation

class JavaScriptAdapter(LanguageAdapter):
    @property
    def language_name(self) -> str:
        return "javascript"

    @property
    def file_extension(self) -> str:
        return ".js"

    def format_signature(self, ir: IntermediateRepresentation) -> str:
        params = [inp.name for inp in ir.inputs]
        return f"function {ir.function_name}({', '.join(params)})"

    def validate_syntax(self, code: str) -> Tuple[bool, Optional[str]]:
        try:
            with tempfile.NamedTemporaryFile("w", suffix=".js", delete=False, encoding="utf-8") as f:
                f.write(code)
                f_name = f.name
            res = subprocess.run(["node", "--check", f_name], capture_output=True, text=True, timeout=5)
            os.remove(f_name)
            if res.returncode == 0:
                return True, None
            return False, res.stderr.strip()
        except Exception as e:
            # Fallback syntax balance validation
            opens = code.count('{') + code.count('(') + code.count('[')
            closes = code.count('}') + code.count(')') + code.count(']')
            if opens != closes:
                return False, f"Unbalanced syntax brackets: {opens} opened vs {closes} closed"
            return True, None

    def generate_test_harness(self, code: str, ir: IntermediateRepresentation) -> str:
        test_cases_json = json.dumps([tc.model_dump() for tc in ir.test_cases])
        
        harness = f'''// Generated by NL2Code Compiler
const assert = require('assert');

{code}

// --- Test Harness ---
const rawTestCases = {test_cases_json};
const results = [];
let passedCount = 0;
let failedCount = 0;

for (const tc of rawTestCases) {{
    const tcId = tc.id;
    const inputArgs = tc.input_args || {{}};
    const expected = tc.expected_output;
    const desc = tc.description || "";
    
    // Extract argument values in order
    const args = Object.values(inputArgs);
    
    try {{
        const actual = {ir.function_name}(...args);
        let isPass = false;
        try {{
            assert.deepStrictEqual(actual, expected);
            isPass = true;
        }} catch(e) {{
            isPass = false;
        }}
        
        if (isPass) {{
            passedCount++;
            results.push({{
                id: tcId,
                status: "pass",
                input: inputArgs,
                expected: expected,
                actual: actual,
                error: null,
                description: desc
            }});
        }} else {{
            failedCount++;
            results.push({{
                id: tcId,
                status: "fail",
                input: inputArgs,
                expected: expected,
                actual: actual,
                error: `Expected ${{JSON.stringify(expected)}} but got ${{JSON.stringify(actual)}}`,
                description: desc
            }});
        }}
    }} catch (err) {{
        failedCount++;
        results.push({{
            id: tcId,
            status: "fail",
            input: inputArgs,
            expected: expected,
            actual: null,
            error: err.message,
            description: desc
        }});
    }}
}}

const summary = {{
    total: rawTestCases.length,
    passed: passedCount,
    failed: failedCount,
    results: results
}};

console.log("__NL2CODE_RESULT_START__");
console.log(JSON.stringify(summary, null, 2));
console.log("__NL2CODE_RESULT_END__");
'''
        return harness

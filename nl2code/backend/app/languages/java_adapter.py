import subprocess
import json
import tempfile
import os
from typing import Tuple, Optional
from nl2code.backend.app.languages.base import LanguageAdapter
from nl2code.backend.app.models.ir import IntermediateRepresentation

class JavaAdapter(LanguageAdapter):
    @property
    def language_name(self) -> str:
        return "java"

    @property
    def file_extension(self) -> str:
        return ".java"

    def format_signature(self, ir: IntermediateRepresentation) -> str:
        type_map = {
            "int": "int",
            "float": "float",
            "double": "double",
            "str": "String",
            "string": "String",
            "bool": "boolean",
            "boolean": "boolean",
            "list": "int[][]",
            "array": "int[]"
        }
        params = []
        for inp in ir.inputs:
            t = type_map.get(inp.type.lower(), "Object")
            params.append(f"{t} {inp.name}")
        ret_type = type_map.get(ir.outputs.type.lower(), "Object")
        return f"public {ret_type} {ir.function_name}({', '.join(params)})"

    def validate_syntax(self, code: str) -> Tuple[bool, Optional[str]]:
        try:
            with tempfile.TemporaryDirectory() as tmpdir:
                file_path = os.path.join(tmpdir, "Solution.java")
                wrapped_code = f"public class Solution {{\n{code}\n}}" if "class Solution" not in code else code
                with open(file_path, "w", encoding="utf-8") as f:
                    f.write(wrapped_code)
                res = subprocess.run(["javac", file_path], capture_output=True, text=True, timeout=5)
                if res.returncode == 0:
                    return True, None
                return False, res.stderr.strip()
        except FileNotFoundError:
            opens = code.count('{') + code.count('(')
            closes = code.count('}') + code.count(')')
            if opens != closes:
                return False, f"Unbalanced braces in Java source: {opens} vs {closes}"
            return True, None
        except Exception as e:
            return False, str(e)


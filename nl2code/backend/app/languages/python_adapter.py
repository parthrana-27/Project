import ast
import json
from typing import Tuple, Optional
from nl2code.backend.app.languages.base import LanguageAdapter
from nl2code.backend.app.models.ir import IntermediateRepresentation

class PythonAdapter(LanguageAdapter):
    @property
    def language_name(self) -> str:
        return "python"

    @property
    def file_extension(self) -> str:
        return ".py"

    def format_signature(self, ir: IntermediateRepresentation) -> str:
        type_map = {
            "int": "int",
            "float": "float",
            "str": "str",
            "string": "str",
            "bool": "bool",
            "boolean": "bool",
            "list": "list",
            "array": "list",
            "dict": "dict",
            "any": "Any"
        }
        params = []
        for inp in ir.inputs:
            t = type_map.get(inp.type.lower(), inp.type)
            params.append(f"{inp.name}: {t}")
        ret_type = type_map.get(ir.outputs.type.lower(), ir.outputs.type)
        return f"def {ir.function_name}({', '.join(params)}) -> {ret_type}:"

    def validate_syntax(self, code: str) -> Tuple[bool, Optional[str]]:
        try:
            ast.parse(code)
            return True, None
        except SyntaxError as e:
            return False, f"SyntaxError at line {e.lineno}, col {e.offset}: {e.msg}"
        except Exception as e:
            return False, str(e)

    def generate_test_harness(self, code: str, ir: IntermediateRepresentation) -> str:
        test_cases_json = json.dumps([tc.model_dump() for tc in ir.test_cases])
        
        harness = f'''# Generated by NL2Code Compiler
import sys
import json
import traceback
from typing import *

{code}

# --- Test Harness ---
raw_test_cases = json.loads({repr(test_cases_json)})
results = []
passed_count = 0
failed_count = 0

def normalize(val):
    if isinstance(val, (set, frozenset)):
        return sorted(list(val))
    if isinstance(val, list):
        try:
            return sorted(val)
        except Exception:
            return val
    return val

for tc in raw_test_cases:
    tc_id = tc.get("id")
    input_args = tc.get("input_args", {{}})
    expected = tc.get("expected_output")
    desc = tc.get("description", "")
    
    try:
        actual = {ir.function_name}(**input_args)
        
        # Check equality with normalization for permutation-independent cases
        is_pass = False
        if actual == expected:
            is_pass = True
        elif isinstance(expected, list) and isinstance(actual, list):
            if normalize(actual) == normalize(expected):
                is_pass = True
        
        if is_pass:
            passed_count += 1
            results.append({{
                "id": tc_id,
                "status": "pass",
                "input": input_args,
                "expected": expected,
                "actual": actual,
                "error": None,
                "description": desc
            }})
        else:
            failed_count += 1
            results.append({{
                "id": tc_id,
                "status": "fail",
                "input": input_args,
                "expected": expected,
                "actual": actual,
                "error": f"AssertionError: Expected {{expected!r}}, got {{actual!r}}",
                "description": desc
            }})
    except Exception as e:
        failed_count += 1
        err_msg = traceback.format_exc().strip().split('\\n')[-1]
        results.append({{
            "id": tc_id,
            "status": "fail",
            "input": input_args,
            "expected": expected,
            "actual": None,
            "error": err_msg,
            "description": desc
        }})

summary = {{
    "total": len(raw_test_cases),
    "passed": passed_count,
    "failed": failed_count,
    "results": results
}}

print("__NL2CODE_RESULT_START__")
print(json.dumps(summary, indent=2))
print("__NL2CODE_RESULT_END__")
'''
        return harness
